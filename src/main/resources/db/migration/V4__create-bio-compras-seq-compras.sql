CREATE SEQUENCE SEQ_TRANSACOES
    START WITH 1
    INCREMENT BY 1
    NOCACHE
  NOCYCLE;

CREATE TABLE BIO_TRANSACOES_COMPRA
(
    ID_TRANSACAO    INTEGER DEFAULT SEQ_TRANSACOES.nextval NOT NULL,
    ID_EMPRESA_COMPRADORA      INTEGER                     NOT NULL,
    ID_CREDITO                 INTEGER NOT NULL,
    QT_COMPRADA     NUMBER(12, 2) NOT NULL,
    VL_TOTAL        NUMBER(12, 2) NOT NULL,
    DT_TRANSACAO    TIMESTAMP NOT NULL,

    CONSTRAINT pk_transacoes_compra
        PRIMARY KEY (ID_TRANSACAO),
    CONSTRAINT fk_compra_empresa
        FOREIGN KEY (ID_EMPRESA_COMPRADORA)
            REFERENCES BIO_EMPRESAS (ID_EMPRESA)
            ON DELETE CASCADE,
    CONSTRAINT fk_compra_credito
        FOREIGN KEY (ID_CREDITO)
            REFERENCES BIO_CREDITOS_CARBONO (ID_CREDITO)
            ON DELETE CASCADE
);