CREATE SEQUENCE SEQ_EMPRESAS
    START WITH 1
    INCREMENT BY 1
    NOCACHE
  NOCYCLE;

CREATE TABLE BIO_EMPRESAS (
    ID_EMPRESA INTEGER DEFAULT SEQ_EMPRESAS.NEXTVAL NOT NULL,
    RAZ_SOCIAL VARCHAR2(100) NOT NULL,
    NR_CNPJ VARCHAR(14) UNIQUE NOT NULL,
    TIP_EMPRESA VARCHAR2(20) NOT NULL,
    DS_SENHA VARCHAR(20) NOT NULL
);