ALTER TABLE BIO_PROJETOS_AMBIENTAIS
    ADD CONSTRAINT pk_projetos PRIMARY KEY (ID_PROJETO);

CREATE SEQUENCE SEQ_CREDITOS
    START WITH 1
    INCREMENT BY 1
    NOCACHE
  NOCYCLE;

CREATE TABLE BIO_CREDITOS_CARBONO
(
    ID_CREDITO                INTEGER DEFAULT SEQ_CREDITOS.nextval NOT NULL,
    ID_PROJETO                INTEGER NOT NULL,
    ANO_CAPTURA               NUMBER(4) NOT NULL,
    COD_HOMOLOGACAO           VARCHAR2(50) NOT NULL UNIQUE,
    QT_TOTAL                  NUMBER(12, 2) NOT NULL,
    QT_DISPONIVEL             NUMBER(12, 2) NOT NULL,
    VL_UNITARIO               NUMBER(10, 2) NOT NULL,

    CONSTRAINT pk_creditos_carbono
        PRIMARY KEY (ID_CREDITO),
    CONSTRAINT fk_cred_carb_proj
        FOREIGN KEY (ID_PROJETO)
            REFERENCES BIO_PROJETOS_AMBIENTAIS (ID_PROJETO)
            ON DELETE CASCADE,
    CONSTRAINT chk_ano_vintage CHECK (ANO_CAPTURA >= 2000),
    CONSTRAINT chk_qtd_total CHECK (QT_TOTAL > 0),
    CONSTRAINT chk_qtd_disponivel CHECK (QT_DISPONIVEL >= 0 AND QT_DISPONIVEL <= QT_TOTAL),
    CONSTRAINT chk_preco_unitario CHECK (VL_UNITARIO > 0)

);